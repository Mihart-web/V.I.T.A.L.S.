/* V.I.T.A.L.S. Digital Twin V10 - layout + clearly labeled V9 training charts.
   Read-only display of V9 synthetic samples; no device/clinical/mission data written. */
(()=>{'use strict';
const $=id=>document.getElementById(id);
const KEY='vitals.digitalTwin.missionSimulation.v9';
const NS='http://www.w3.org/2000/svg';
const METRICS=[
 {id:'dtv9ChartHR',key:'hr',name:'Heart rate',unit:'bpm',color:'#65ebcb',low:40,high:170},
 {id:'dtv9ChartSpo',key:'spo',name:'Oxygen saturation',unit:'%',color:'#7cbaff',low:82,high:100},
 {id:'dtv9ChartMuscle',key:'muscle',name:'Muscle activation',unit:'a.u.',color:'#ffd09b',low:0,high:100},
 {id:'dtv10ChartResp',key:'resp',name:'Respiration',unit:'/min',color:'#6ce6d9',low:6,high:45},
 {id:'dtv10ChartTemp',key:'temp',name:'Skin temperature',unit:'°C',color:'#f6c583',low:25,high:43},
 {id:'dtv10ChartCognitive',key:'cognitive',name:'Cognitive proxy',unit:'% (illustrative)',color:'#b5a1f5',low:0,high:100}
];
const mk=(tag,attrs={},text)=>{const x=document.createElementNS(NS,tag);for(const [k,v] of Object.entries(attrs))x.setAttribute(k,String(v));if(text!==undefined)x.textContent=String(text);return x};
const num=x=>x!==null&&x!==undefined&&x!==''&&Number.isFinite(Number(x))?Number(x):null;
const range=(x,a,b)=>Math.max(a,Math.min(b,x));
function readSeries(){let record;try{record=JSON.parse(localStorage.getItem(KEY)||'{}')}catch{return []}
 const missionId=(()=>{try{return JSON.parse(localStorage.getItem('vitals.mission.active.v1')||'null')?.id||''}catch{return ''}})();
 const astronautId=$('astronaut')?.value||'';
 const stored=record?.[`${missionId}::${astronautId}`]?.samples;
 return (Array.isArray(stored)?stored:[]).filter(x=>x&&x.classification==='synthetic_training_v9'&&x.astronautId===astronautId&&x.missionId===missionId).slice(-100);
}
function layout(){const main=document.querySelector('.maincol');const stage=main?.querySelector('.stage');const sim=$('dtv9Control');if(!main||!stage||!sim)return false;
 if(stage.nextElementSibling!==sim)main.insertBefore(stage,sim);
 if(!$('dtv10Label')){const h=document.createElement('p');h.id='dtv10Label';h.className='dtv10-note';h.textContent='Simulation graphs: generated by Digital Twin V9. These are NOT observations from Wrist Monitor, BioLoad, cognitive games or real sensors.';
 sim.querySelector('.dtv9-livecharts')?.before(h);}
 const charts=sim.querySelector('.dtv9-livecharts');if(charts){for(const m of METRICS.slice(3)){if($(m.id))continue;const card=document.createElement('article');const title=document.createElement('h3');title.textContent=m.name+' ';const small=document.createElement('small');small.textContent=m.unit;title.appendChild(small);const svg=mk('svg',{id:m.id,viewBox:'0 0 450 130',role:'img','aria-label':m.name+' V9 synthetic training chart'});card.append(title,svg);charts.append(card)}}
 const recorded=$('heartChart')?.closest('.panel');if(recorded&&!$('dtv10RecordedNote')){const note=document.createElement('p');note.id='dtv10RecordedNote';note.className='dtv10-note dtv10-recorded';note.innerHTML='The two charts below show <strong>device-recorded observations only</strong>. They may correctly say “Not enough recorded observations” when you have only used the Digital Twin simulator. <a href="#dtv9Control">Go to the six V9 simulation charts</a>.';
 recorded.querySelector('.charts')?.before(note)}return true;
}
function plot(m,samples){const svg=$(m.id);if(!svg)return;
 // Plot V9-only observations, explicitly named as synthetic training series.
 svg.replaceChildren();const left=44,right=436,top=13,bottom=105;
 for(let i=0;i<=4;i++){const y=top+(bottom-top)*i/4;svg.append(mk('line',{x1:left,y1:y,x2:right,y2:y,stroke:'#2a5764','stroke-width':1}));const n=m.high-(m.high-m.low)*i/4;svg.append(mk('text',{x:39,y:y+4,'text-anchor':'end',fill:'#87abb5','font-size':10},Number.isInteger(n)?n:n.toFixed(1)))}
 if(!samples.length){svg.append(mk('text',{x:242,y:63,'text-anchor':'middle',fill:'#9ac4ce','font-size':12},'No V9 simulation samples yet'));return}
 const valid=samples.map((v,i)=>({n:num(v[m.key]),i})).filter(p=>p.n!==null);
 if(!valid.length){svg.append(mk('text',{x:242,y:63,'text-anchor':'middle',fill:'#9ac4ce','font-size':12},'No values for this signal'));return}
 const X=i=>samples.length===1?left+(right-left)/2:left+(right-left)*i/(samples.length-1);
 const Y=n=>bottom-range((n-m.low)/(m.high-m.low),0,1)*(bottom-top);
 const pts=valid.map(p=>`${X(p.i)},${Y(p.n)}`).join(' ');
 if(valid.length>1)svg.append(mk('polyline',{points:pts,stroke:m.color,'stroke-width':2.9,fill:'none','stroke-linejoin':'round','stroke-linecap':'round'}));
 const latest=valid[valid.length-1];svg.append(mk('circle',{cx:X(latest.i),cy:Y(latest.n),r:4.5,fill:m.color,stroke:'#102d39','stroke-width':1.4}));
 const val=latest.n;svg.append(mk('text',{x:435,y:120,'text-anchor':'end',fill:m.color,'font-size':11,'font-weight':700},`${val.toFixed(1)} ${m.unit}`));
 if(valid.length===1)svg.append(mk('text',{x:242,y:83,'text-anchor':'middle',fill:'#9ac4ce','font-size':10},'First sample · next reading in ~2 s'));
}
let lastSignature='',lastContext='';
function refresh(){if(!layout())return;const samples=readSeries();const chip=$('dtv9Chip')?.textContent||'';const mode=$('dtv9Mode')?.value||'';
 const currentContext=($('astronaut')?.value||'')+'|'+(document.querySelector('#dtv9Mission')?.textContent||'');
 const active=chip==='LIVE SYNTHETIC DEMO';
 if(active&&mode==='live'){
  // V9's own update() may replace the chart before this pass. Always repaint while active.
  for(const m of METRICS)plot(m,samples.slice(-60));
 }else if(mode==='history'){
  const signature=currentContext+'|'+samples.length+'|'+(samples[samples.length-1]?.timestamp||'');
  if(signature!==lastSignature||currentContext!==lastContext){for(const m of METRICS)plot(m,samples.slice(-60));lastSignature=signature}
 }else{
  // Baseline/recorded mode does not claim a live simulation. Show no live chart data.
  if(lastSignature!=='baseline'){for(const m of METRICS)plot(m,[]);lastSignature='baseline'}
 }
 lastContext=currentContext;
 const badge=$('dtv10Label');if(badge)badge.textContent=`DIGITAL TWIN SIMULATION · ${samples.length} stored V9 training samples for the selected astronaut / mission · ${active?'LIVE':'NOT LIVE'} · NOT SENSOR TELEMETRY`;
}
function boot(){if(!layout()){setTimeout(boot,160);return}
 // If V9 has saved samples, show history immediately rather than an empty graph on reload.
 const mode=$('dtv9Mode');if(mode&&mode.value==='baseline'&&readSeries().length){mode.value='history';mode.dispatchEvent(new Event('change',{bubbles:true}))}
 refresh();setInterval(refresh,1300);
 $('astronaut')?.addEventListener('change',()=>{lastSignature='';setTimeout(refresh,80)});
 mode?.addEventListener('change',()=>{lastSignature='';setTimeout(refresh,80)});
}
if(document.readyState==='loading')document.addEventListener('DOMContentLoaded',boot,{once:true});else boot();
})();
